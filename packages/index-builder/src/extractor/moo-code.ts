export function serverStartedCode(nonce: string): string[] {
  const stateName = `__moo_rag_server_started_${nonce}`;
  return [
    'wizard = verb_info(#0, "server_started")[1];',
    "original_max_object = max_object();",
    `startup_state = #0.(${mooString(stateName)});`,
    `delete_property(#0, ${mooString(stateName)});`,
    "if (startup_state[1])",
    '  set_verb_args(#0, "server_started", startup_state[3]);',
    '  restore_errors = set_verb_code(#0, "server_started", startup_state[4]);',
    '  if (restore_errors) raise(E_INVARG, "Cannot restore server_started", restore_errors); endif',
    '  set_verb_info(#0, "server_started", startup_state[2]);',
    "else",
    '  delete_verb(#0, "server_started");',
    "endif",
    "handler = create(#-1, #-1);",
    'handler.name = "MOO RAG one-shot extraction handler";',
    `add_property(handler, "nonce", ${mooString(nonce)}, {wizard, "r"});`,
    'add_property(handler, "claimed", 0, {wizard, "rw"});',
    'add_property(handler, "original_max_object", original_max_object, {wizard, "r"});',
    'add_verb(handler, {wizard, "rxd", "json_string"}, {"this", "none", "this"});',
    `errors = set_verb_code(handler, "json_string", ${mooList(JSON_STRING_CODE)});`,
    'if (errors) raise(E_INVARG, "Cannot install json_string", errors); endif',
    'add_verb(handler, {wizard, "rxd", "emit"}, {"this", "none", "this"});',
    `errors = set_verb_code(handler, "emit", ${mooList(EMIT_CODE)});`,
    'if (errors) raise(E_INVARG, "Cannot install emit", errors); endif',
    'add_verb(handler, {wizard, "rxd", "render_help"}, {"this", "none", "this"});',
    `errors = set_verb_code(handler, "render_help", ${mooList(RENDER_HELP_CODE)});`,
    'if (errors) server_log(tostr("MOO_RAG_INJECT_ERROR ", handler.nonce, " ", toliteral(errors))); return; endif',
    'add_verb(handler, {wizard, "rxd", "dump"}, {"this", "none", "this"});',
    `errors = set_verb_code(handler, "dump", ${mooList(DUMP_CODE)});`,
    'if (errors) server_log(tostr("MOO_RAG_INJECT_ERROR ", handler.nonce, " ", toliteral(errors))); return; endif',
    'add_verb(handler, {wizard, "rxd", "do_login_command"}, {"this", "none", "this"});',
    `errors = set_verb_code(handler, "do_login_command", ${mooList(LOGIN_CODE)});`,
    'if (errors) raise(E_INVARG, "Cannot install do_login_command", errors); endif',
    "port = listen(handler, 0, 0);",
    `server_log(tostr("MOO_RAG_READY ", ${mooString(nonce)}, " ", port));`,
    "return;",
  ];
}

export function emergencyInjection(nonce: string): string {
  const stateName = `__moo_rag_server_started_${nonce}`;
  return [
    `;;`,
    `original_info = \`verb_info(#0, "server_started") ! E_VERBNF => 0';`,
    `if (!original_info)`,
    `  add_property(#0, ${mooString(stateName)}, {0}, {player, "r"});`,
    `  add_verb(#0, {player, "rxd", "server_started"}, {"this", "none", "this"});`,
    `else`,
    `  original_args = verb_args(#0, "server_started");`,
    `  original_code = verb_code(#0, "server_started", 0, 1);`,
    `  add_property(#0, ${mooString(stateName)}, {1, original_info, original_args, original_code}, {player, "r"});`,
    `  set_verb_info(#0, "server_started", {player, "rxd", "server_started"});`,
    `endif`,
    `server_log(tostr("MOO_RAG_PREPARED ", ${mooString(nonce)}));`,
    `return;`,
    `.`,
    `.program #0:server_started`,
    ...serverStartedCode(nonce),
    `.`,
    `continue`,
    "",
  ].join("\n");
}
